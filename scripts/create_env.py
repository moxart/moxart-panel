"""Write a .env with freshly generated secrets. Never overwrites an existing file."""
import secrets
import sys
from pathlib import Path

ENV_PATH = Path(__file__).resolve().parent.parent / '.env'


def token():
    return secrets.token_urlsafe(48)


def main():
    if ENV_PATH.exists():
        print('.env already exists, leaving it untouched')
        return

    admin_password = secrets.token_urlsafe(12)

    ENV_PATH.write_text('''# generated by scripts/create_env.py -- keep this file private
MYSQL_DATABASE=moxart
MYSQL_USER=moxart
MYSQL_PASSWORD={mysql}
MYSQL_ROOT_PASSWORD={mysql_root}

MOXART_SECRET_KEY={secret}
MOXART_JWT_SECRET_KEY={jwt}
MOXART_SECURITY_PASSWORD_SALT={salt}

MOXART_SERVER_BASE_URL=http://localhost:5000
MOXART_MAIL_DEFAULT_SENDER=noreply@moxart.local

MOXART_ADMIN_USERNAME=moxart
MOXART_ADMIN_EMAIL=admin@moxart.local
MOXART_ADMIN_PASSWORD={admin}
'''.format(mysql=token(), mysql_root=token(), secret=token(), jwt=token(), salt=token(), admin=admin_password))
    ENV_PATH.chmod(0o600)

    print('wrote .env')
    print('admin login: moxart / {}'.format(admin_password))


if __name__ == '__main__':
    sys.exit(main())
